use Tests\TestCase;

class EmployeeCreationTest extends TestCase
{
    use RefreshDatabase;

    protected function setUp(): void
    {
        parent::setUp();

        // Create roles
        Role::firstOrCreate(['id' => 1, 'name' => 'SuperAdmin']);
        Role::firstOrCreate(['id' => 2, 'name' => 'CompanyAdmin']);
        Role::firstOrCreate(['id' => 3, 'name' => 'HR']);
        Role::firstOrCreate(['id' => 4, 'name' => 'Employee']);
    }

    public function test_company_admin_can_create_hr_employee_with_autogenerated_id_and_company_assignment(): void
    {
        $companyUser = User::factory()->create([
            'role_id' => 2, // CompanyAdmin
            'role' => 'company',
        ]);
        $company = Company::create([
            'user_id' => $companyUser->id,
            'name' => 'Acme Corporation',
            'company_code' => 'COMP-0001',
            'email' => 'acme@test.com',
            'status' => 1,
        ]);
        $companyUser->update(['company_id' => $company->id]);

        $this->actingAs($companyUser);

        $response = $this->post(route('storeEmployee'), [
            'name' => 'John HR',
            'email' => 'john.hr@acme.com',
            'phone' => '1234567890',
            'password' => 'InitialPassword123!',
            'password_confirmation' => 'InitialPassword123!',
            'role' => 'hr',
            'address' => '123 Street City',
            'age' => '30',
        ]);

        $response->assertRedirect(route('employee'));

        $user = User::withoutGlobalScopes()->where('email', 'john.hr@acme.com')->first();
        $this->assertNotNull($user);
        $this->assertEquals($company->id, $user->company_id);
        $this->assertEquals('hr', $user->role);

        $employee = Employee::where('e_user_id', $user->id)->first();
        $this->assertNotNull($employee);
        $this->assertEquals($companyUser->id, $employee->owner_user_id);
        $this->assertStringStartsWith('EMP-', $employee->id_number);
    }

