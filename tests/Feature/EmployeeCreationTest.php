        ]);

        $this->actingAs($companyUser1);

        $response = $this->get(route('employee'));
        $response->assertStatus(200);
        $response->assertSee('EMP-9999');
    }

    public function test_can_delete_employee(): void
    {
        $companyUser = User::factory()->create(['role_id' => 2, 'role' => 'company']);
        $company = Company::create([
            'user_id' => $companyUser->id,
            'name' => 'Delete Co',
            'company_code' => 'COMP-0003',
            'email' => 'deleteco@test.com',
            'status' => 1,
        ]);
        $companyUser->update(['company_id' => $company->id]);

        $hrUser = User::factory()->create([
            'role_id' => 3,
            'role' => 'hr',
            'company_id' => $company->id,
        ]);
        $employee = Employee::create([
            'owner_user_id' => $companyUser->id,
            'e_user_id' => $hrUser->id,
            'designation' => 'Hr',
            'id_number' => 'EMP-0099',
            'status' => 1,
        ]);

        $this->actingAs($companyUser);

        $response = $this->delete(route('deleteEmployee', $hrUser->id));
        $response->assertRedirect(route('employee'));

        $this->assertNull(User::withoutGlobalScopes()->find($hrUser->id));
        $this->assertNull(Employee::find($employee->id));
    }

    public function test_super_admin_can_view_all_employees_and_filter_by_company_and_role(): void
    {
        $superAdmin = User::factory()->create([
            'role_id' => 1,
            'role' => 'admin',
        ]);

        $comp1Owner = User::factory()->create(['role_id' => 2, 'role' => 'company']);
        $company1 = Company::create([
            'user_id' => $comp1Owner->id,
            'name' => 'Alpha Inc',
            'company_code' => 'ALPHA-001',
            'email' => 'alpha@test.com',
            'status' => 1,
        ]);

        $comp2Owner = User::factory()->create(['role_id' => 2, 'role' => 'company']);
        $company2 = Company::create([
            'user_id' => $comp2Owner->id,
            'name' => 'Beta Corp',
            'company_code' => 'BETA-002',
            'email' => 'beta@test.com',
            'status' => 1,
        ]);

        $hrUser1 = User::factory()->create([
            'name' => 'Alpha HR User',
            'email' => 'hr@alpha.com',
            'role_id' => 3,
            'role' => 'hr',
            'company_id' => $company1->id,
        ]);
        Employee::create([
            'owner_user_id' => $comp1Owner->id,
            'e_user_id' => $hrUser1->id,
            'designation' => 'Hr',
            'id_number' => 'EMP-ALPHA-HR',
            'status' => 1,
        ]);

        $staffUser2 = User::factory()->create([
            'name' => 'Beta Staff User',
            'email' => 'staff@beta.com',
            'role_id' => 4,
            'role' => 'employee',
            'company_id' => $company2->id,
        ]);
        Employee::create([
            'owner_user_id' => $comp2Owner->id,
            'e_user_id' => $staffUser2->id,
            'designation' => 'Employee',
            'id_number' => 'EMP-BETA-STAFF',
            'status' => 1,
        ]);

        $this->actingAs($superAdmin);

        // View all employees across companies
        $response = $this->get(route('employee'));
        $response->assertStatus(200);
        $response->assertSee('EMP-ALPHA-HR');
        $response->assertSee('EMP-BETA-STAFF');

        // Filter by company (first filter)
        $filterCompanyResponse = $this->get(route('employee', ['company_id' => $company1->id]));
        $filterCompanyResponse->assertStatus(200);
        $filterCompanyResponse->assertSee('EMP-ALPHA-HR');
        $filterCompanyResponse->assertDontSee('EMP-BETA-STAFF');

        // Filter by role (second filter)
        $filterRoleResponse = $this->get(route('employee', ['role' => 'employee']));
        $filterRoleResponse->assertStatus(200);
        $filterRoleResponse->assertDontSee('EMP-ALPHA-HR');
        $filterRoleResponse->assertSee('EMP-BETA-STAFF');
    }

    public function test_manually_inserted_sql_users_and_masters_are_visible_on_employee_page(): void
    {
        $superAdmin = User::factory()->create(['role_id' => 1, 'role' => 'admin']);
        $company = Company::create([
            'user_id' => $superAdmin->id,
            'name' => 'SQL Direct Co',
            'company_code' => 'SQL-001',
            'email' => 'sql@test.com',
            'status' => 1,
        ]);

        // Direct SQL insert simulation for User (missing Employees entry)
        $manualUser = User::create([
            'name' => 'SQL Manual User',
            'email' => 'sqlmanual@test.com',
            'password' => \Illuminate\Support\Facades\Hash::make('password123'),
            'role' => 'employee',
            'role_id' => 4,
            'company_id' => $company->id,
        ]);

        // Direct SQL insert simulation for EmployeeMaster (missing User/Employee entry)
        $manualMaster = \App\Models\EmployeeMaster::create([
            'company_id' => $company->id,
            'employee_code' => 'EMP-SQL-99',
            'first_name' => 'SQLFirst',
            'last_name' => 'SQLLast',
            'email' => 'sqlmaster@test.com',
            'position' => 'Developer',
            'date_hired' => '2026-01-01',
            'status' => 'active',
        ]);

        // Explicitly reconcile unlinked identities using the Artisan command
        $this->artisan('payroll:reconcile-employee-identities --apply')
            ->assertExitCode(0);

        $this->actingAs($superAdmin);

        $response = $this->get(route('employee'));
        $response->assertStatus(200);
        $response->assertSee('SQL Manual User');
        $response->assertSee('sqlmaster@test.com');
    }
