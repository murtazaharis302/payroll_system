    public function test_employee_index_renders_safely_even_if_user_relation_is_missing(): void
    {
        $companyUser1 = User::factory()->create(['role_id' => 2, 'role' => 'company']);
        $company1 = Company::create([
            'user_id' => $companyUser1->id,
            'name' => 'Company One',
            'company_code' => 'COMP-0001',
            'email' => 'comp1@test.com',
            'status' => 1,
        ]);
        $companyUser1->update(['company_id' => $company1->id]);

        $companyUser2 = User::factory()->create(['role_id' => 2, 'role' => 'company']);
        $company2 = Company::create([
            'user_id' => $companyUser2->id,
            'name' => 'Company Two',
            'company_code' => 'COMP-0002',
            'email' => 'comp2@test.com',
            'status' => 1,
        ]);
        $companyUser2->update(['company_id' => $company2->id]);

        $targetUser = User::factory()->create([
            'role_id' => 3,
            'role' => 'hr',
            'company_id' => $company2->id, // Belongs to Company 2
        ]);

        Employee::create([
